using System;
using System.Collections.Generic;
using UnityEngine;

namespace Ushqyr.Track.Geo
{
    /// <summary>A building footprint (local metres, x east, y north) with its height.</summary>
    [Serializable]
    public sealed class GeoBuilding
    {
        public long Id;
        public string Name = "";
        /// <summary>The OSM building=* value (yes, apartments, office, ...).</summary>
        public string Kind = "yes";
        public int Levels;
        public float Height;
        /// <summary>True when the height came from the defaults, not from OSM tags.</summary>
        public bool HeightEstimated;
        /// <summary>Generated by a hero generator (sphere, pavilions, pods) instead of the generic extruder.</summary>
        public bool Hero;
        public string HeroRole = "";
        public List<Vector2> Footprint = new List<Vector2>();
        /// <summary>Inner rings (courtyards) of multipolygon buildings.</summary>
        public List<GeoRing> Holes = new List<GeoRing>();
    }

    /// <summary>A closed ring of points (a courtyard hole).</summary>
    [Serializable]
    public sealed class GeoRing
    {
        public List<Vector2> Points = new List<Vector2>();
    }

    /// <summary>A road centreline.</summary>
    [Serializable]
    public sealed class GeoRoad
    {
        public long Id;
        public string Name = "";
        /// <summary>The OSM highway=* value (primary, residential, footway, ...).</summary>
        public string Kind = "";
        public int Lanes;
        /// <summary>Carriageway width in metres (tagged, or from lanes / the kind).</summary>
        public float Width;
        public bool OneWay;
        /// <summary>A pedestrian crossing (footway=crossing / crossing=*): drawn as a zebra.</summary>
        public bool Crossing;
        public List<Vector2> Points = new List<Vector2>();
    }

    /// <summary>A polygon area: park, grass, parking, water, playground, ...</summary>
    [Serializable]
    public sealed class GeoArea
    {
        public long Id;
        public string Kind = "";
        public List<Vector2> Polygon = new List<Vector2>();
    }

    /// <summary>Everything the district builders need from the OSM extract, in local metres.</summary>
    [Serializable]
    public sealed class GeoData
    {
        public double OriginLat, OriginLon;
        public string Timestamp = "";
        public List<GeoBuilding> Buildings = new List<GeoBuilding>();
        public List<GeoRoad> Roads = new List<GeoRoad>();
        public List<GeoArea> Areas = new List<GeoArea>();
        public List<Vector2> Trees = new List<Vector2>();
    }
}
